export function buildUserPrompt(req: WriteRequest): string {
  const s = req.store
  const lines: string[] = []

  lines.push(`## 이번 글`)
  lines.push(`- 유형: ${POST_TYPE_LABEL[req.type]}`)
  lines.push(`- 메인 키워드: ${req.mainKeyword}`)
  if (req.subKeywords.filter(Boolean).length)
    lines.push(`- 함께 찾는 키워드: ${req.subKeywords.filter(Boolean).join(', ')}`)
  if (req.localKeyword) lines.push(`- 지역 키워드(조연): ${req.localKeyword}`)

  if (req.type === 'review') {
    lines.push(
      req.sponsorship === 'sponsored'
        ? '- 대가성: 협찬(제공받음). **첫 화면(후킹 앞이나 직후)에 제공받아 작성한 후기임을 명확히 표기하고, 해시태그에 #협찬후기 를 넣는다.**'
        : /*
           * **「내돈내산」이라는 말을 모델에게 주지 않는다.**
           *
           * 화자 지시(VOICE.review)에서는 「내돈내산을 쓰지 않는다」고 못박아 뒀는데 여기서는
           * 「대가성: 내돈내산」이라고 알려주고 있었다. 서로 반대말이라 모델이 해시태그에
           * #내돈내산 을 넣어버렸다 — 센터가 작성한 글에서는 사실이 아니다.
           * 그래서 상태를 사실대로만 말하고, 그 말을 쓰지 말라고 함께 준다.
           */
          '- 대가성: 대가를 받지 않은 글이다. 협찬 표기를 넣지 않는다. 다만 **"내돈내산", "제 돈으로", "직접 결제했다" 같은 말을 본문·해시태그에 쓰지 않는다** — 이 글은 센터가 작성하므로 사실이 아니다. "제공받았다"는 뉘앙스도 쓰지 않는다.'
    )
  }

  /*
   * 정보 구간의 주제를 회원이 지정할 수 있게 한다 (2026-08-10).
   *
   * 회원 요청 — "현재 나오는 글이 24시 운영으로 되어 있는데 정보성란을 내가 원하는 주제로
   * 넣을 수 있는지." 지시문은 「주제를 하나만 잡는다」까지만 말하고 **어느 주제인지는 AI 가
   * 골랐다.** 그래서 매번 24시 운영·시간대 이야기로 수렴했다 (키워드가 그쪽이니까).
   */
  if (req.infoTopic?.trim()) {
    lines.push(
      '',
      '## 운동 정보 구간의 주제 (이것만 다룬다)',
      req.infoTopic.trim(),
      '다른 주제로 새지 않는다. 이 주제 안에서 서로 다른 정보가 5종류 이상 나오게 쓴다.'
    )
  }

  /*
   * **회원 요청은 맨 마지막에, 우선한다고 못박아 둔다.**
   *
   * 회원 요청 — "이런 식으로 해달라고 하는 요청칸이 있으면 좋겠어." 매번 대화로 말하던 것을
   * 화면에 남기는 자리다. 지시문 끝에 두는 이유는 모델이 뒤쪽을 더 강하게 따르기 때문이고,
   * 「형식 규칙과 부딪히면 형식을 지킨다」를 함께 적어 검수가 깨지지 않게 한다.
   */
  if (req.request?.trim()) {
    lines.push(
      '',
      '## 이번 글 요청 (다른 지시보다 우선한다)',
      req.request.trim(),
      '단, 위의 **형식 규칙**(글자수·키워드 횟수·소제목 수)과 **쓰지 말아야 하는 표현**은 그대로 지킨다 — 그건 기계가 검사한다.'
    )
  }

  if (req.eventText?.trim()) {
    lines.push('', '## 진행 중인 이벤트 (가감 없이 그대로 쓴다)', req.eventText.trim())
    /*
     * 이벤트 훅을 **따로** 한 번 더 적는다.
     *
     * 골격 지시문 1단계에 이미 들어 있는데도 나온 글에 훅이 없었다 (회원 지적). 긴 단계
     * 설명의 끝에 붙어 있으면 묻힌다. 이벤트가 실제로 있는 글에서만, 제목을 달아 따로 낸다.
     * 검수의 `event-hook` 항목이 같은 것을 잰다 — 지시와 검사가 어긋나면 안 된다.
     */
    if (req.type === 'promo') {
      lines.push(
        '',
        '### 이벤트 훅 (첫 구간에 반드시 넣는다)',
        '- 후킹 마지막에 **한 문장**으로 흘린다: 「무엇이 있다」 + 「제한이 있다」.',
        '- 예) "8월 등록분만 3개월 이용권을 10만 원 아래로 맞췄어요. 다만 인원을 정해둬서 조건은 아래에 정리해뒀습니다."',
        '- 「이벤트 진행 중입니다」·「혜택을 준비했습니다」는 훅이 아니다 — 무엇이 걸렸는지 없으면 읽을 이유가 안 생긴다.',
        '- 정확한 인원 수·마감일·포함 항목은 이벤트 구간에 남긴다. 첫 구간에서 다 밝히면 뒤를 읽을 이유가 없어진다.'
      )
    }
  } else {
    lines.push('', '## 이벤트', '없음 — 이벤트 구간을 쓰지 말고 그 분량을 다른 구간에 나눈다.')
  }

  if (s) {
    lines.push('', '## 지점 정보 (여기에 없는 것은 쓰지 않는다)')
    lines.push(`- 정식 상호명: ${s.legalName || s.name}`)
    lines.push(`- 표시 이름: ${s.name}`)
    if (s.womenOnly) lines.push('- 여성전용 지점 — 남성 대상 표현을 쓰지 않는다.')
    lines.push(`- 24시간 운영: ${s.open24 ? '예' : '아니오'}`)
    if (s.location) lines.push(`- 위치: ${s.location}`)
    if (s.features?.length) lines.push(`- 시설 특징:\n${s.features.map((f) => `  · ${f}`).join('\n')}`)
    if (s.strengths?.length) lines.push(`- 고유 강점:\n${s.strengths.map((f) => `  · ${f}`).join('\n')}`)
    if (s.phone) lines.push(`- 전화: ${s.phone}`)
    if (s.reserveUrl) lines.push(`- 예약 링크: ${s.reserveUrl}`)
    if (s.memo) lines.push(`- 메모: ${s.memo}`)
    lines.push('- 트레이너 정보는 주어지지 않았다 — PT·트레이너 관련 서술을 만들지 않는다.')
  } else {
    lines.push('', '## 지점 정보', '없음 — 지점 고유 정보가 필요한 서술을 하지 않는다.')
  }

  if (req.prescription?.length) {
    /*
     * **유형에 맞게 걸러서 넣는다.** 처방은 키워드 단위로 저장되어 글 유형을 모른다.
     * 걸러내지 않으면 「우리도 방문 후기 형태로 맞붙어라」가 홍보글 지시문으로 가고,
     * 실제로 그래서 홍보글이 후기 톤으로 나왔다 (prescriptionForType 주석 참고).
     */
    const rx = prescriptionForType(req.prescription, req.type)
    if (rx.length) {
      lines.push('', '## 상위노출 분석 결과 (이 조건을 맞춘다)')
      for (const p of rx.slice(0, 6)) lines.push(`- ${p}`)
    }
  }

  if (req.recent?.length) {
    lines.push('', '## 우리 블로그 최근 글 (지점이 달라도 겹치지 않게 각도를 바꾼다)')
    for (const r of req.recent.slice(0, 5)) {
      const bits = [POST_TYPE_LABEL[r.type], r.mainKeyword, r.introType, r.angle].filter(Boolean)
      const where = r.storeName ? `[${r.storeName}] ` : ''
      lines.push(`- ${where}${r.title || '(제목 없음)'} — ${bits.join(' / ')}`)
    }
    lines.push(
      '도입 방식·주력 앵글·소제목이 위 글들과 겹치면 유사문서로 묶인다. 다르게 잡는다.',
      '**지점이 다르다는 것은 이유가 되지 않는다.** 지점명·지역명만 바꾼 글은 실측에서 90.4% 가 글자 그대로 같았다 — 같은 사업자의 복제 문서로 묶일 수 있고, 지역 키워드가 다른데 본문이 같으면 그 검색 의도에 답하지 못한다.'
    )
  }

  lines.push('', 'JSON 객체 하나만 출력한다.')
  return lines.join('\n')
}


/*
 * 목록에서 **뺀 것과 그 이유** — 다시 넣고 싶어질 때 보라고 남긴다.
 *
 *   개선  — 「자세가 개선됩니다」는 우리도 쓰는 말이다. 어려운 말이 아니다.
 *   난이  — 「난이도」가 걸린다. 흔한 말을 오탐으로 잡는다.
 *   코르티솔·렙틴·그렐린·인슐린 — 다이어트 글에서 실제로 쓰는 말이고, 회원도 그 낱말이
 *          든 글에는 아무 말 하지 않았다. 어려워 보인다고 다 막으면 정보가 얕아진다.
 *   분·초·시간 — 시간 단위는 한글이 자연스럽다 (「15분」이 「15min」보다 낫다).
 *   프로그램·인스타그램 — 「그램」이 들어 있지만 앞이 한글이라 안 걸린다 (findHardWords 주석).
 */

export interface HardWordHit extends HardWord {
  /** 글에 실제로 나온 모양 (조사가 붙어 있을 수 있다) */
  found: string
}

/**
 * 글에서 어려운 낱말을 찾는다.
 *
 * 낱말 뒤에 조사가 붙는다 (「낙폭에서」·「낙폭이」). 그래서 낱말로 시작하는 덩어리를 찾되,
 * **앞은 한글이 아니어야 한다** — 「반등」을 막으면서 「일반등급」까지 잡히면 안 된다.
 */
export function findHardWords(text: string): HardWordHit[] {
  const hay = text ?? ''
  const hits: HardWordHit[] = []
  for (const w of HARD_WORDS) {
    // 앞: 한글이 아닌 것(또는 글 시작) / 뒤: 조사·어미가 붙을 수 있다
    const re = new RegExp(`(^|[^가-힣])(${w.word}[가-힣]{0,3})`, 'g')
    const m = re.exec(hay)
    if (m) hits.push({ ...w, found: m[2] })
  }
  return hits
}

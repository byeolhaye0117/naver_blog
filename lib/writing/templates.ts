/**
 * 안내 줄(`> `)을 제거해 네이버에 붙일 본문만 남긴다.
 *
 * `[이미지: …]` · `[영상: …]` 표기는 **남긴다** — 그게 어디에 무엇을 올려야 하는지
 * 알려주는 자리표이고, 복사 패키지(export.ts)가 그 자리를 따로 뽑아 안내한다.
 */
export function stripGuides(body: string): string {
  return body
    .split(/\r?\n/)
    .filter((l) => !/^\s*>\s/.test(l))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

export function hasGuides(body: string): boolean {
  return /^\s*>\s/m.test(body)
}

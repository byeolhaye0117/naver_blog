import type { PostType, Store } from '@/lib/types'

/**
 * 글 골격 생성.
 *
 * `> ` 로 시작하는 줄은 작성 안내(가이드)다. 글자수·키워드 계산에는 포함되지만
 * 복사 패키지를 만들 때 자동으로 제거되므로 네이버에는 붙지 않는다.
 * 실제로는 안내를 지우면서 그 자리에 본문을 채우는 방식으로 쓴다.
 */

export interface TemplateContext {
  store?: Store
  mainKeyword: string
  subKeywords: string[]
  localKeyword?: string
  eventText?: string
}

function guide(s: string): string {
  return `> ${s}`
}

export function buildTemplate(type: PostType, ctx: TemplateContext): string {
  switch (type) {
    case 'promo':
      return promoTemplate(ctx)
    case 'info':
      return infoTemplate(ctx)
    case 'review':
      return reviewTemplate(ctx)
  }
}

